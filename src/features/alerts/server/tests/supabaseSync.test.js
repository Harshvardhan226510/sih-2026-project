describe('isolation — sync does not touch local pipeline', () => {
  it('supabaseSync.js does not import notificationRouter', async () => {
    // This test ensures no accidental coupling to the notification path.
    // We verify by checking the module's imports don't reference the router.
    const { readFileSync } = await import('fs');
    const { resolve, dirname } = await import('path');
    const { fileURLToPath } = await import('url');

    const __dirname = dirname(fileURLToPath(import.meta.url));
    const syncFile = resolve(__dirname, '../services/supabaseSync.js');
    const src = readFileSync(syncFile, 'utf-8');

    expect(src).not.toContain('notificationRouter');
    expect(src).not.toContain('mqttService');
    expect(src).not.toContain('webPush');
    expect(src).not.toContain('deliveryService');
  });

  it('supabaseSync.js does not import from db/connection (read path)', async () => {
    const { readFileSync } = await import('fs');
    const { resolve, dirname } = await import('path');
    const { fileURLToPath } = await import('url');

    const __dirname = dirname(fileURLToPath(import.meta.url));
    const syncFile = resolve(__dirname, '../services/supabaseSync.js');
    const src = readFileSync(syncFile, 'utf-8');

    // supabaseSync should not query the local DB — it only maps provided objects
    expect(src).not.toContain("from '../db/connection");
  });
});
