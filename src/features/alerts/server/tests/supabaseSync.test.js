/**
 * Supabase Sync Unit Tests
 *
 * Tests the Supabase shared-data sync layer in isolation.
 * Uses in-memory mocks — no real Supabase connection required.
 *
 * Test coverage (maps to requirements 1–12):
 *   1.  New local alert is representable in Supabase (field mapping check)
 *   2.  Local alert.id maps correctly to Supabase external_id
 *   3.  Repeated sync calls upsert (not duplicate-insert) — idempotency
 *   4.  Alert update triggers an upsert with changed fields
 *   5.  Extreme severity is accepted without normalisation error
 *   6.  area and area_code are present in the synced payload
 *   7.  Status ACTIVE/EXPIRED/CANCELLED all pass through correctly
 *   8.  Supabase client unavailable → sync returns early, no error thrown
 *   9.  Supabase network error → sync logs and returns without throwing
 *   10. polygonToWkt converts JSON lat/lon pairs to PostGIS WKT correctly
 *   11. polygonToWkt handles null/invalid gracefully (returns null)
 *   12. _mapAlertToSupabase produces all expected fields
 *
 * NOT tested here (tested by existing test files):
 *   - Dashboard read path  (reliability.test.js)
 *   - MQTT / Web Push      (mqtt-webpush.test.js)
 *   - FAST/SLOW behaviour  (reliability.test.js)
 *   - Alert ingestion flow (reliability.test.js / processing.test.js)
 */

