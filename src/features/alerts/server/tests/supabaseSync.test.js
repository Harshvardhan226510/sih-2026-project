// ─── Minimal alert fixture ────────────────────────────────────────────────────

function makeAlert(overrides = {}) {
  return {
    id:           overrides.id          ?? 'imd-IMD-CAP-TEST-001',
    source:       overrides.source      ?? 'imd',
    sourceId:     overrides.sourceId    ?? 'IMD-CAP-TEST-001',
    event:        overrides.event       ?? 'Heavy Rainfall',
    headline:     overrides.headline    ?? 'Heavy Rainfall Warning',
    description:  overrides.description ?? 'Heavy rainfall expected in coastal districts.',
    severity:     overrides.severity    ?? 'Severe',
    status:       overrides.status      ?? 'ACTIVE',
    area:         overrides.area        ?? 'Dakshina Kannada, Karnataka',
    areaCode:     overrides.areaCode    ?? 'DAKSHINA KANNADA',
    latitude:     overrides.latitude    ?? 12.86,
    longitude:    overrides.longitude   ?? 74.84,
    polygon:      overrides.polygon     ?? null,
    language:     overrides.language    ?? 'en',
    effectiveAt:  overrides.effectiveAt ?? '2026-01-01T00:00:00Z',
    expiresAt:    overrides.expiresAt   ?? '2099-12-31T00:00:00Z',
    issuedAt:     overrides.issuedAt    ?? '2026-01-01T00:00:00Z',
    createdAt:    overrides.createdAt   ?? '2026-01-01T00:00:00Z',
    updatedAt:    overrides.updatedAt   ?? '2026-01-01T00:00:00Z',
    ...overrides,
  };
}

// ─────────────────────────────────────────────────────────────────────────────
// Field mapping tests (_mapAlertToSupabase)
// ─────────────────────────────────────────────────────────────────────────────

describe('_mapAlertToSupabase — field mapping', () => {
  // Test 1: New local alert produces a valid Supabase payload
  it('maps a new local alert to a valid Supabase row payload', () => {
    const alert = makeAlert();
    const row   = _mapAlertToSupabase(alert);

    expect(row).not.toBeNull();
    expect(row.external_id).toBeDefined();
    expect(row.type).toBe('Heavy Rainfall');
    expect(row.title).toBe('Heavy Rainfall Warning');
    expect(row.severity).toBe('Severe');
    expect(row.status).toBe('ACTIVE');
    expect(row.source).toBe('imd');
    expect(row.language).toBe('en');
    expect(row.updated_at).toBeDefined();
  });

  // Test 2: Local alert.id maps to external_id
  it('maps local alert.id to Supabase external_id', () => {
    const alert = makeAlert({ id: 'imd-IMD-CAP-XYZ-999' });
    const row   = _mapAlertToSupabase(alert);

    expect(row.external_id).toBe('imd-IMD-CAP-XYZ-999');
    // Supabase UUID id is NOT present in the payload — it is generated by Postgres
    expect(row.id).toBeUndefined();
  });

  // Test 3: Payload is idempotent — mapping the same alert twice gives same external_id
  it('mapping the same alert twice produces the same external_id (idempotency)', () => {
    const alert = makeAlert();
    const row1  = _mapAlertToSupabase(alert);
    const row2  = _mapAlertToSupabase(alert);

    expect(row1.external_id).toBe(row2.external_id);
    // type, severity, status should be the same
    expect(row1.type).toBe(row2.type);
    expect(row1.severity).toBe(row2.severity);
  });

  // Test 4: Updated alert fields are reflected in the payload
  it('maps updated alert fields correctly', () => {
    const original = makeAlert({ severity: 'Moderate', status: 'ACTIVE' });
    const updated  = makeAlert({ severity: 'Extreme',  status: 'ACTIVE', description: 'Cyclonic storm approaching.' });

    const rowOriginal = _mapAlertToSupabase(original);
    const rowUpdated  = _mapAlertToSupabase(updated);

    expect(rowOriginal.severity).toBe('Moderate');
    expect(rowUpdated.severity).toBe('Extreme');
    expect(rowUpdated.description).toBe('Cyclonic storm approaching.');
  });

  // Test 5: Extreme severity passes through correctly
  it('accepts Extreme severity without normalisation error', () => {
    const alert = makeAlert({ severity: 'Extreme' });
    const row   = _mapAlertToSupabase(alert);

    expect(row.severity).toBe('Extreme');
  });

  // Test 6: area and area_code are present
  it('includes area and area_code in the synced payload', () => {
    const alert = makeAlert({
      area:     'Dakshina Kannada, Karnataka',
      areaCode: 'DAKSHINA KANNADA',
    });
    const row = _mapAlertToSupabase(alert);

    expect(row.area).toBe('Dakshina Kannada, Karnataka');
    expect(row.area_code).toBe('DAKSHINA KANNADA');
  });

  // Test 7: All valid statuses pass through
  it.each([['ACTIVE'], ['EXPIRED'], ['CANCELLED']])(
    'passes status %s through correctly',
    (status) => {
      const alert = makeAlert({ status });
      const row   = _mapAlertToSupabase(alert);
      expect(row.status).toBe(status);
    }
  );

  // Test 12: All expected Supabase columns are present
  it('produces all expected Supabase columns', () => {
    const alert = makeAlert();
    const row   = _mapAlertToSupabase(alert);

    const expectedKeys = [
      'external_id', 'type', 'title', 'description',
      'severity', 'status', 'source', 'source_id',
      'language', 'area', 'area_code',
      'latitude', 'longitude', 'region_geom',
      'valid_from', 'valid_to', 'issued_at',
      'created_at', 'updated_at',
    ];

    for (const key of expectedKeys) {
      expect(row, `missing key: ${key}`).toHaveProperty(key);
    }
  });

  // Test: handles missing alert gracefully
  it('returns null for a null alert', () => {
    expect(_mapAlertToSupabase(null)).toBeNull();
  });

  it('returns null for an alert missing id', () => {
    expect(_mapAlertToSupabase({ event: 'test' })).toBeNull();
  });

  // Test: handles repo-style snake_case aliases (from repository SELECT … AS)
  it('handles snake_case aliases from repository queries', () => {
    const repoAlert = {
      id:           'imd-REPO-001',
      source:       'imd',
      source_id:    'REPO-001',
      event:        'Cyclone Warning',
      severity:     'Extreme',
      status:       'ACTIVE',
      area:         'Chennai, Tamil Nadu',
      area_code:    'CHENNAI',
      latitude:     13.08,
      longitude:    80.27,
      language:     'en',
      effective_at: '2026-01-01T00:00:00Z',
      expires_at:   '2099-01-01T00:00:00Z',
      issued_at:    '2026-01-01T00:00:00Z',
      created_at:   '2026-01-01T00:00:00Z',
      updated_at:   '2026-01-01T00:00:00Z',
    };
    const row = _mapAlertToSupabase(repoAlert);
    expect(row.external_id).toBe('imd-REPO-001');
    expect(row.source_id).toBe('REPO-001');
    expect(row.severity).toBe('Extreme');
  });
});

