describe('syncAlertToSupabase — Supabase client handling', () => {
  let originalModule;

  beforeEach(async () => {
    // Import the client module so we can mock it
    originalModule = await import('../db/supabaseClient.js');
    vi.resetModules();
  });

  afterEach(() => {
    vi.restoreAllMocks();
  });

  // Test 8: Supabase client unavailable → returns early without throwing
  it('returns early when Supabase client is null (credentials not set)', async () => {
    // Mock getSupabaseClient to return null
    vi.doMock('../db/supabaseClient.js', () => ({
      getSupabaseClient: () => null,
    }));

    // Dynamic import after mock
    const { syncAlertToSupabase: syncFn } = await import('../services/supabaseSync.js');

    const alert = makeAlert();
    // Must not throw
    await expect(syncFn(alert, 'created')).resolves.toBeUndefined();
  });

  // Test 9a: Supabase upsert returns an error → logs but does not throw
  it('handles Supabase API error without throwing', async () => {
    const mockUpsert = vi.fn().mockResolvedValue({ error: { message: 'connection refused', code: '500' } });
    const mockFrom   = vi.fn().mockReturnValue({ upsert: mockUpsert });

    vi.doMock('../db/supabaseClient.js', () => ({
      getSupabaseClient: () => ({ from: mockFrom }),
    }));

    const { syncAlertToSupabase: syncFn } = await import('../services/supabaseSync.js');

    const alert = makeAlert();
    await expect(syncFn(alert, 'created')).resolves.toBeUndefined();
  });

  // Test 9b: Supabase client throws a network error → logs but does not throw
  it('handles network-level exception without throwing', async () => {
    const mockUpsert = vi.fn().mockRejectedValue(new Error('Network timeout'));
    const mockFrom   = vi.fn().mockReturnValue({ upsert: mockUpsert });

    vi.doMock('../db/supabaseClient.js', () => ({
      getSupabaseClient: () => ({ from: mockFrom }),
    }));

    const { syncAlertToSupabase: syncFn } = await import('../services/supabaseSync.js');

    const alert = makeAlert();
    await expect(syncFn(alert, 'created')).resolves.toBeUndefined();
  });

  // Test 3 (runtime): Repeated sync does not call insert twice — uses upsert with onConflict
  it('calls upsert with onConflict=external_id for idempotency', async () => {
    const mockUpsert = vi.fn().mockResolvedValue({ error: null });
    const mockFrom   = vi.fn().mockReturnValue({ upsert: mockUpsert });

    vi.doMock('../db/supabaseClient.js', () => ({
      getSupabaseClient: () => ({ from: mockFrom }),
    }));

    const { syncAlertToSupabase: syncFn } = await import('../services/supabaseSync.js');

    const alert = makeAlert();
    await syncFn(alert, 'created');
    await syncFn(alert, 'created'); // second call simulates repeated sync

    expect(mockUpsert).toHaveBeenCalledTimes(2);
    // Both calls must use onConflict: 'external_id'
    for (const call of mockUpsert.mock.calls) {
      expect(call[1]).toEqual({ onConflict: 'external_id' });
    }
  });
});

