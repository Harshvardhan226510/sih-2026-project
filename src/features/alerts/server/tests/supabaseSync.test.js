// syncAlertsToSupabase — batch handling
// ─────────────────────────────────────────────────────────────────────────────

describe('syncAlertsToSupabase — batch sync', () => {
  it('maps multiple alerts to valid Supabase payloads (batch mapping contract)', () => {
    // Verify the payload structure that syncAlertsToSupabase would upsert.
    // We test _mapAlertToSupabase directly since that is the core logic —
    // the batch function adds only the upsert call on top.
    const alerts = [
      makeAlert({ id: 'imd-A1', sourceId: 'A1' }),
      makeAlert({ id: 'imd-A2', sourceId: 'A2', severity: 'Extreme' }),
      makeAlert({ id: 'imd-A3', sourceId: 'A3', status: 'EXPIRED' }),
    ];

    const payloads = alerts.map(_mapAlertToSupabase);
    expect(payloads).toHaveLength(3);
    expect(payloads.every(Boolean)).toBe(true);

    // external_id values must be distinct and match local alert ids
    expect(payloads[0].external_id).toBe('imd-A1');
    expect(payloads[1].external_id).toBe('imd-A2');
    expect(payloads[2].external_id).toBe('imd-A3');

    // Extreme severity passes through
    expect(payloads[1].severity).toBe('Extreme');

    // EXPIRED status passes through
    expect(payloads[2].status).toBe('EXPIRED');

    // No Supabase UUID in the payload — Postgres generates it
    expect(payloads.every(p => p.id === undefined)).toBe(true);
  });

  it('each batch payload has external_id as the dedup key', () => {
    const alerts = [
      makeAlert({ id: 'imd-B1', severity: 'Extreme' }),
      makeAlert({ id: 'imd-B2', status: 'EXPIRED' }),
    ];
    const payloads = alerts.map(_mapAlertToSupabase);
    expect(payloads[0].external_id).toBe('imd-B1');
    expect(payloads[1].external_id).toBe('imd-B2');
  });

  it('syncAlertsToSupabase resolves for empty array without throwing', async () => {
    // Must not throw regardless of client availability
    await expect(syncAlertsToSupabase([], 'expired')).resolves.toBeUndefined();
  });

  it('syncAlertsToSupabase resolves for non-empty array without throwing (no client)', async () => {
    // When client is null (no credentials configured), must silently resolve
    const alerts = [makeAlert({ id: 'imd-C1' })];
    await expect(syncAlertsToSupabase(alerts, 'expired')).resolves.toBeUndefined();
  });
});

