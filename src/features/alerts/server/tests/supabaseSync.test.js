describe('polygonToWkt — coordinate conversion', () => {
  // Test 10: Valid polygon JSON → WKT
  it('converts a valid JSON lat/lon polygon to PostGIS WKT', () => {
    const polygon = JSON.stringify([
      { lat: 12.0, lon: 74.0 },
      { lat: 13.0, lon: 74.0 },
      { lat: 13.0, lon: 75.0 },
      { lat: 12.0, lon: 75.0 },
    ]);
    const wkt = polygonToWkt(polygon);

    expect(wkt).not.toBeNull();
    expect(wkt).toMatch(/^POLYGON\(\(/);
    // Coordinates should be lon lat (PostGIS order)
    expect(wkt).toContain('74 12');
    expect(wkt).toContain('74 13');
    // Ring must be closed
    const inner = wkt.replace('POLYGON((', '').replace('))', '');
    const pairs = inner.split(', ');
    expect(pairs[0]).toBe(pairs[pairs.length - 1]);
  });

  // Test 11a: null polygon → null
  it('returns null for null polygon', () => {
    expect(polygonToWkt(null)).toBeNull();
  });

  // Test 11b: empty string → null
  it('returns null for empty string', () => {
    expect(polygonToWkt('')).toBeNull();
  });

  // Test 11c: invalid JSON → null
  it('returns null for invalid JSON', () => {
    expect(polygonToWkt('not-json')).toBeNull();
  });

  // Test 11d: fewer than 3 points → null (not a polygon)
  it('returns null for fewer than 3 coordinate pairs', () => {
    const tooFew = JSON.stringify([{ lat: 1, lon: 2 }, { lat: 3, lon: 4 }]);
    expect(polygonToWkt(tooFew)).toBeNull();
  });

  // Test 11e: non-numeric coordinates → null
  it('returns null when coordinates are non-numeric', () => {
    const bad = JSON.stringify([
      { lat: 'a', lon: 74 },
      { lat: 13, lon: 74 },
      { lat: 13, lon: 75 },
    ]);
    expect(polygonToWkt(bad)).toBeNull();
  });

  it('already-closed ring is not double-closed', () => {
    const polygon = JSON.stringify([
      { lat: 12.0, lon: 74.0 },
      { lat: 13.0, lon: 74.0 },
      { lat: 13.0, lon: 75.0 },
      { lat: 12.0, lon: 74.0 }, // already closed
    ]);
    const wkt = polygonToWkt(polygon);
    // Should still be valid and not have an extra pair
    expect(wkt).toMatch(/^POLYGON\(\(/);
  });
});

